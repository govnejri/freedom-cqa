  var dicts = { ru: ru };
  var LOCALES = { ru: 'ru-RU', kk: 'kk-KZ', en: 'en-US' };
  var LCID = { 1049: 'ru', 1087: 'kk', 1033: 'en' };
  var lang = 'ru';
  var pluralRules = {};

  function plural(n, forms) {
    var loc = LOCALES[lang] || 'ru-RU';
    var pr = pluralRules[loc] || (pluralRules[loc] = new Intl.PluralRules(loc));
    var cat = pr.select(Number(n));
    var idx = { one: 0, few: 1, many: 2, other: 2 }[cat];
    if (idx == null) idx = forms.length - 1;
    return forms[Math.min(idx, forms.length - 1)];
  }

  function format(s, params) {
    if (!params) return s;
    return s.replace(/\{(\w+)((?:\|[^|}]*)+)?\}/g, function (m, name, forms) {
      if (!(name in params)) return m;
      var v = params[name];
      if (forms) return v + ' ' + plural(v, forms.slice(1).split('|'));
      return v == null ? '' : String(v);
    });
  }

  function lookup(key) {
    var d = dicts[lang];
    if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
    if (Object.prototype.hasOwnProperty.call(ru, key)) return ru[key];
    return null;
  }

  function t(key, params) {
    var s = lookup(key);
    if (s == null) {
      if (CQA.debug) console.warn('[i18n] нет ключа', key);
      return key;
    }
    return format(s, params);
  }

  /** Перевод с запасным значением для динамических ключей (статусы с бэкенда). */
  function tx(key, fallback, params) {
    var s = lookup(key);
    return s == null ? fallback : format(s, params);
  }

  function init() {
    var sp = new URLSearchParams(location.search);
    var want = sp.get('lang') || LCID[sp.get('userlcid') || sp.get('userLcid')] || null;
    try { want = want || localStorage.getItem('cqa.lang'); } catch (e) { /* нет доступа */ }
    if (want && dicts[want]) lang = want;
  }

  CQA.t = t;
  CQA.i18n = {
    t: t, tx: tx, init: init, plural: plural,
    lang: function () { return lang; },
    locale: function () { return LOCALES[lang] || 'ru-RU'; },
    add: function (code, dict) { dicts[code] = Object.assign(dicts[code] || {}, dict); },
    dicts: dicts
  };
